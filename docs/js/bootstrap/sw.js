const APP_ORIGIN               = self.location.origin;
// A content-hash in the filename makes an asset immutable under that name → cache-first forever.
const IMMUTABLE_HASH_RE        = /\.[0-9a-f]{8,}\.(?:js|mjs|wasm|css)$/i;
// wasm-pack's pkg output (vdg_freight.js / _bg.wasm) is NOT hash-named — but it IS precached and
// versioned with STATIC_CACHE (a redeploy bumps 7a6cbda → activate drops the old cache →
// install re-precaches the new bytes), so it's served cache-first, never network-first. The multi-MB
// wasm through _networkFirst's 3.5s abort could hand WebAssembly.compile a 503 Offline: the main
// thread cached it first, but the SQLite worker's concurrent boot fetch raced the timeout and got a
// dead 503 ("compile … HTTP status not ok"). Cache-first has no timeout and stays fresh via the version.
const PKG_BUNDLE_RE            = /\/pkg\/vdg_freight(?:_bg\.wasm|\.js)$/;
const NETWORK_FIRST_TIMEOUT_MS = 15000;

function isHashedImmutable(pathname) { return IMMUTABLE_HASH_RE.test(pathname); }
function isSameOrigin(url)          { return url === APP_ORIGIN || url.startsWith(APP_ORIGIN + '/'); }

// Only http(s) requests belong in the Cache API. A chrome-extension:, blob:, or data: request
// (e.g. a wallet extension's inpage.js) throws "Request scheme … is unsupported" in Cache.put,
// so the SW must step aside for anything that isn't http(s).
const HTTP_SCHEMES = ['http:', 'https:'];

function isHttpScheme(url) { return HTTP_SCHEMES.includes(new URL(url).protocol); }

// Cross-origin AND host-matched: a same-origin URL (all of js/**, the app shell) can
// never be a Google auth endpoint, no matter what its path looks like. Same-origin must
// always fall through to the normal network-first-then-cache strategy so it's servable
// offline from the precache — that's what boot needs token-refresh.js for.
function isGoogleAuthEndpoint(url) {
  if (isSameOrigin(url)) return false;
  const { hostname } = new URL(url);
  return AUTH_HOSTS.includes(hostname);
}

// ── install ───────────────────────────────────────────────────────────────────

self.addEventListener('install', (ev) => {
  ev.waitUntil(
    caches.open(STATIC_CACHE).then((cache) =>
      Promise.allSettled(
        STATIC_ASSETS.map((rel) => cache.add(new URL(rel, self.registration.scope).href))
      )
    )
  );
  // No auto-skipWaiting: the new worker parks in `waiting` when a controller already
  // exists, so the client can prompt the user instead of forcing a reload mid-edit.
});

// ── activate ──────────────────────────────────────────────────────────────────

self.addEventListener('activate', (ev) => {
  ev.waitUntil(
    caches.keys().then(async (keys) => {
      const validCaches = [STATIC_CACHE, DRIVE_META_CACHE];
      const hadOldGeneration = keys.some((k) => !validCaches.includes(k));
      await Promise.all(
        keys.filter((k) => !validCaches.includes(k)).map((k) => caches.delete(k))
      );
      await self.clients.claim();
      // Deploy heals every open tab, not just the one that fetched the new build: a tab still
      // running an OLD bundle holds the exclusive OPFS sahpool outside the leader-election bus,
      // starving every store op in the new tab (stuck license gate, silent 8s timeouts). Reload
      // the old tabs into this build so the lock is released and they rejoin the bus. Gated on
      // an old cache generation existing — a first-ever install has nothing to heal, no reload.
      if (hadOldGeneration) {
        const cs = await self.clients.matchAll({ type: 'window' });
        await Promise.all(cs.map((c) =>
          // WindowClient.navigate is Chromium-only ground; elsewhere the store-locked screen
          // still surfaces the manual instruction, so a missing navigate is a degrade, not a throw.
          typeof c.navigate === 'function' ? c.navigate(c.url).catch(() => { /* client gone mid-reload */ }) : null
        ));
      }
    })
  );
});

// ── message ───────────────────────────────────────────────────────────────────

// Client-triggered activation: sent only after the user clicks the update banner.
self.addEventListener('message', (ev) => {
  if (ev.data?.type === 'SKIP_WAITING') self.skipWaiting();
  // F-34-01: main thread already computed the due-soon payload — the SW only shows it.
  if (ev.data?.type === DUE_SOON_NOTIFY_MSG) {
    const { title, groups = [] } = ev.data;
    const p = Promise.all(groups.map((g) =>
      self.registration.showNotification(title, { body: g.body, tag: g.tag })));
    if (ev.waitUntil) ev.waitUntil(p);
  }
});

// ── payment due-soon (F-34-01, notify-only) ─────────────────────────────────────
// The SW never computes, never opens IndexedDB, never imports — it only shows notifications
// from a payload the main thread already built, or wakes a live client to run its own
// compute (bootstrap/platform/sync-due-soon.js). A closed-tab wakeup with no client is a no-op, never a
// throw (AC-04).
async function _wakeClientsForDueSoon() {
  const cs = await self.clients.matchAll({ type: 'window' });
  cs.forEach((c) => c.postMessage({ type: DUE_SOON_WAKE_MSG }));
}

// Tier 1 — SW Periodic Background Sync (needs installed PWA + granted permission; nice-to-
// have per F-54, registration lives in sw-register.js). Under Option A this degrades to a
// closed-tab no-op (no client to wake) — accepted per F-2/AC-04.
self.addEventListener('periodicsync', (ev) => {
  if (ev.tag === DUE_SOON_SYNC_TAG) ev.waitUntil(_wakeClientsForDueSoon());
});

// Tier 2(b) — opportunistic one-off Background Sync (Chromium-only, no PWA/PBS permission
// needed).
self.addEventListener('sync', (ev) => {
  if (ev.tag === DUE_SOON_SYNC_TAG) ev.waitUntil(_wakeClientsForDueSoon());
});

// ── fetch ─────────────────────────────────────────────────────────────────────

self.addEventListener('fetch', (ev) => {
  const { request } = ev;
  const url = request.url;

  // Non-http(s) schemes (chrome-extension:, blob:, data:) can't go through the Cache API —
  // step aside so cache.put never throws "scheme unsupported".
  if (!isHttpScheme(url)) return;

  // Pass through: real Google auth endpoints only (never same-origin app files)
  if (isGoogleAuthEndpoint(url)) return;

  // Pass through: Drive file content (IDB is content cache)
  if (DRIVE_CONTENT_RE.test(url)) return;

  // Only GET responses are cacheable — a POST (Drive upload/create) must never reach _swr or
  // _cacheFirst, where cache.put throws "Request method 'POST' is unsupported".
  if (request.method !== 'GET') return;

  // Stale-while-revalidate: Drive metadata
  if (url.startsWith(DRIVE_META_HOST)) {
    ev.respondWith(_swr(request));
    return;
  }

  // Cross-origin: the vdg-server API is dynamic data — caching it serves a stale workspace
  // (reads miss fresh writes, etag CAS 412s forever). Pass it through untouched. Only the
  // version-pinned CDN libs stay cache-first (immutable by URL → offline-capable).
  if (!isSameOrigin(url)) {
    if (new URL(url).pathname.startsWith(API_PATH_PREFIX)) return;
    ev.respondWith(_cacheFirst(request));
    return;
  }

  // Content-hash-named asset → cache-first (a rebuild changes the name, so never stale)
  const { pathname } = new URL(url);
  // Same-origin API (vdg-server serving its own bundle) — same rule as cross-origin: never cached.
  if (pathname.startsWith(API_PATH_PREFIX)) return;
  if (isHashedImmutable(pathname)) {
    ev.respondWith(_cacheFirst(request));
    return;
  }

  // Everything else same-origin (app modules, entrypoint, shell, wasm pkg) is
  // network-first: a redeploy is served immediately; cache is only the offline fallback.
  ev.respondWith(_networkFirst(request));
});

async function _cacheFirst(request) {
  const cache  = await caches.open(STATIC_CACHE);
  const cached = await cache.match(request);
  if (cached) return cached;
  try {
    const network = await fetch(request);
    if (network?.ok) cache.put(request, network.clone());
    return network;
  } catch {
    return new Response('Offline', { status: 503 });
  }
}

async function _networkFirst(request) {
  const cache = await caches.open(STATIC_CACHE);
  try {
    const network = await fetch(request);
    if (network?.ok) cache.put(request, network.clone());
    return network;
  } catch {
    const cached = await cache.match(request);
    if (cached) return cached;
    return new Response('Offline', { status: 503 });
  }
}

async function _swr(request) {
  const cache   = await caches.open(DRIVE_META_CACHE);
  const cached  = await cache.match(request);
  const now     = Date.now();

  if (cached) {
    const dateHeader = cached.headers.get('Date');
    const cacheAge   = dateHeader ? now - new Date(dateHeader).getTime() : Infinity;
    if (cacheAge < DRIVE_META_TTL_MS) {
      _revalidateInBackground(cache, request);
      return cached;
    }
    // Stale: revalidate and return stale while waiting
    _revalidateInBackground(cache, request);
    return cached;
  }

  // No cache — fetch network
  const response = await fetch(request).catch(() => null);
  if (response?.ok) cache.put(request, response.clone());
  return response || new Response('Offline', { status: 503 });
}

function _revalidateInBackground(cache, request) {
  fetch(request)
    .then((res) => { if (res?.ok) cache.put(request, res); })
    .catch(() => { /* network error during background revalidation — ignore */ });
}
